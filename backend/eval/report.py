"""Regenerate docs/METRICS.md from the latest eval results."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from eval.golden import RESULTS_DIR
from eval.metrics import METRIC_DEFINITIONS

REPO_ROOT = Path(__file__).resolve().parents[2]
METRICS_PATH = REPO_ROOT / "docs" / "METRICS.md"

# Issue #24 does not set numeric targets. VISION.md starting points stay there.
TARGETS: dict[str, str] = {
    "recall_at_5": "TBD",
    "citation_accuracy": "TBD",
    "refusal_correctness": "TBD",
    "uncited_number_count": "TBD",
    "latency_p50_ms": "TBD",
    "latency_p95_ms": "TBD",
}

METRIC_ROWS: tuple[tuple[str, str, str], ...] = (
    ("recall_at_5", "recall@5", "rate"),
    ("citation_accuracy", "citation accuracy", "rate"),
    ("refusal_correctness", "refusal correctness", "rate"),
    ("uncited_number_count", "uncited-number count", "count"),
    ("latency_p50_ms", "latency p50 (ms)", "latency"),
    ("latency_p95_ms", "latency p95 (ms)", "latency"),
)


class ResultsError(ValueError):
    """Results JSON is missing or does not have the harness metrics."""


def latest_results_path(results_dir: Path = RESULTS_DIR) -> Path:
    files = sorted(path for path in results_dir.glob("*.json") if path.is_file())
    if not files:
        raise ResultsError(f"no results JSON in {results_dir}")

    def sort_key(path: Path) -> tuple[str, str]:
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return ("", path.name)
        stamp = payload.get("generated_at") if isinstance(payload, dict) else ""
        return (stamp if isinstance(stamp, str) else "", path.name)

    return max(files, key=sort_key)


def load_results(path: Path) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ResultsError(f"{path} is not JSON") from exc
    if not isinstance(payload, dict):
        raise ResultsError(f"{path} is not an object")
    metrics = payload.get("metrics")
    if not isinstance(metrics, dict):
        raise ResultsError(f"{path} is missing metrics")
    missing = [key for key, _, _ in METRIC_ROWS if key not in metrics]
    if missing:
        raise ResultsError(f"{path} is missing {', '.join(missing)}")
    return payload


def render_metrics_markdown(payload: dict[str, Any], *, source: Path) -> str:
    metrics = payload["metrics"]
    date = _result_date(payload, source)
    rows = [
        "| Metric | Target | Current value | Date |",
        "| --- | --- | --- | --- |",
    ]
    for key, label, kind in METRIC_ROWS:
        rows.append(
            "| "
            + " | ".join(
                (
                    label,
                    TARGETS[key],
                    _format_value(metrics[key], kind),
                    date,
                )
            )
            + " |"
        )
    definitions = [
        f"- **{label}.** {METRIC_DEFINITIONS[label]}"
        for _, label, _ in METRIC_ROWS
    ]
    source_text = _source_label(source)
    header = [
        "# Metrics",
        "",
        f"Generated by `make metrics` from `{source_text}`.",
        (
            f"Run time: `{payload.get('generated_at', 'unknown')}`. "
            f"Runner: `{payload.get('runner', 'unknown')}`. "
            f"Subset: `{payload.get('subset', 'unknown')}`. "
            f"Questions scored: {payload.get('case_count', 'unknown')}. "
            f"Uncited-number counter: `{payload.get('uncited_number_counter', 'unknown')}`."
        ),
        "Do not edit this file by hand.",
        "",
        "Targets are `TBD` where the eval issue does not set one.",
        "",
        *rows,
        "",
        "## Definitions",
        "",
        *definitions,
        "",
    ]
    return "\n".join(header)


def render_job_summary(payload: dict[str, Any]) -> str:
    metrics = payload["metrics"]
    lines = [
        "### Eval subset",
        "",
        "| Metric | Value |",
        "| --- | --- |",
    ]
    for key, label, kind in METRIC_ROWS:
        lines.append(f"| {label} | {_format_value(metrics[key], kind)} |")
    lines.extend(
        [
            "",
            (
                f"Golden file: `{payload.get('golden_path', 'unknown')}` "
                f"({_subset_label(payload)}, "
                f"{payload.get('case_count', 'unknown')} questions). "
                f"Runner: `{payload.get('runner', 'unknown')}`."
            ),
            "",
        ]
    )
    return "\n".join(lines)


def write_metrics_document(
    results_path: Path,
    destination: Path | None = None,
) -> Path:
    payload = load_results(results_path)
    target = destination or METRICS_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        render_metrics_markdown(payload, source=results_path),
        encoding="utf-8",
    )
    return target


def _subset_label(payload: dict[str, Any]) -> str:
    subset = payload.get("subset")
    if subset == "ci":
        return "ci subset"
    if subset == "full":
        return "full set"
    return "unknown subset"


def _format_value(value: Any, kind: str) -> str:
    if value is None:
        return "not available"
    if kind == "count":
        return str(int(value))
    if kind == "latency":
        return f"{float(value):.3f}"
    return f"{float(value):.4f}"


def _result_date(payload: dict[str, Any], source: Path) -> str:
    explicit = payload.get("date")
    if isinstance(explicit, str) and len(explicit) >= 10:
        return explicit[:10]
    generated = payload.get("generated_at")
    if isinstance(generated, str) and len(generated) >= 10:
        return generated[:10]
    return source.stem


def _source_label(source: Path) -> str:
    try:
        return source.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return source.as_posix()


def main() -> int:
    path = latest_results_path()
    destination = write_metrics_document(path)
    print(f"Wrote {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
